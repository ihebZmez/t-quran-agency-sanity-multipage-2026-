import {defineField, defineType} from 'sanity'

export default defineType({
  name: 'service',
  title: 'البرامج وحلقات التحفيظ',
  type: 'document',
  fields: [
    defineField({
      name: 'title',
      title: 'اسم البرنامج',
      type: 'string',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'slug',
      title: 'الرابط المختصر',
      type: 'slug',
      options: {source: 'title'},
      validation: (Rule) => Rule.required(),
    }),
    defineField({name: 'shortDescription', title: 'نبذة قصيرة', type: 'text', rows: 3}),
    defineField({name: 'description', title: 'تفاصيل البرنامج', type: 'text', rows: 6}),
    defineField({
      name: 'icon',
      title: 'أيقونة',
      type: 'string',
      description: 'اسم أيقونة من Lucide أو رمز تعبيري',
    }),
    defineField({
      name: 'coverImage',
      title: 'صورة البرنامج',
      type: 'image',
      options: {hotspot: true},
    }),
    defineField({
      name: 'heroImage',
      title: 'صورة رئيسية',
      type: 'image',
      options: {hotspot: true},
    }),
    defineField({
      name: 'category',
      title: 'التصنيف',
      type: 'string',
      options: {
        list: [
          'تحفيظ',
          'تجويد',
          'تفسير',
          'دورات صيفية',
          'حلقات نسائية',
          'حلقات للأطفال',
          'أنشطة ومسابقات',
          'تكوين المعلمين',
          'محاضرات ودروس',
          'رحلات وأنشطة تربوية',
        ],
      },
    }),
    defineField({
      name: 'audience',
      title: 'الفئة المستهدفة',
      type: 'string',
      options: {
        list: [
          {title: 'النساء', value: 'women'},
          {title: 'الرجال', value: 'men'},
          {title: 'الأطفال', value: 'children'},
          {title: 'الجميع', value: 'all'},
        ],
        layout: 'radio',
      },
      validation: (Rule) => Rule.required(),
    }),
    defineField({name: 'schedule', title: 'موعد الحلقة', type: 'string'}),
    defineField({name: 'location', title: 'مكان الحلقة', type: 'string'}),
    defineField({
      name: 'registrationInstructions',
      title: 'تعليمات التسجيل',
      type: 'text',
      rows: 3,
    }),
    defineField({
      name: 'registrationOpen',
      title: 'التسجيل مفتوح',
      type: 'boolean',
      initialValue: false,
    }),
    defineField({
      name: 'features',
      title: 'Fonctionnalités',
      type: 'array',
      of: [{type: 'string'}],
    }),
    defineField({name: 'benefits', title: 'Bénéfices', type: 'array', of: [{type: 'string'}]}),
    defineField({name: 'commentDemarrer', title: 'Comment démarrer', type: 'text', rows: 3}),
    defineField({
      name: 'accompanimentOptions',
      title: "Options d'accompagnement",
      type: 'array',
      of: [{type: 'string'}],
    }),
    defineField({name: 'ctaLabel', title: 'Texte du CTA', type: 'string'}),
    defineField({name: 'ctaLink', title: 'Lien du CTA', type: 'url'}),
    defineField({name: 'order', title: 'ترتيب العرض', type: 'number', initialValue: 0}),
    defineField({
      name: 'active',
      title: 'نشر على الموقع',
      type: 'boolean',
      initialValue: true,
    }),
  ],
  orderings: [{title: 'Ordre', name: 'orderAsc', by: [{field: 'order', direction: 'asc'}]}],
  preview: {select: {title: 'title', subtitle: 'category', media: 'coverImage'}},
})
